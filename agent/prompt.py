# --------------------------------------------------------------------------- #
# 摘要压缩（滚动进行，每压一次花一次模型调用）
# --------------------------------------------------------------------------- #

#: 摘要器的系统提示。要点是**只留事实、丢掉客套**，并且明确写出保留范围——
#: 「尽量保留重要信息」这种话模型执行不了，「用户偏好、关键实体、已确认的结论」
#: 这样的清单才可以逐条对照。
SUMMARY_SYSTEM = """你在压缩一段对话历史，把它并入已有的摘要。

只保留这几类信息：
1. 用户的偏好、习惯、明确说过的好恶
2. 关键实体：人名、项目名、文件名、地名、型号、数字（金额、版本号、日期）
3. 已经确认的结论和答案
4. 尚未解决、用户可能还要追问的问题

一律丢掉：寒暄、客套、重复表述、工具的中间过程、模型的自我说明。
不要写「用户询问了……」这种转述，直接写事实本身。
用第三人称陈述句，不要分点编号，写成一到两段连续的短文。"""

#: 摘要器的用户提示。``previous`` 是已有摘要（第一次压缩时是一句占位），
#: ``transcript`` 是这次新挤出窗口的对话，``limit`` 是字数上限。
SUMMARY_USER = """【已有摘要】
{previous}

【这次要并进去的新对话】
{transcript}

把上面两部分合成一段新的摘要，{limit} 字以内。只输出摘要正文，不要任何前后缀。"""


# --------------------------------------------------------------------------- #
# 长期记忆的抽取（每轮回答之后跑一次，命中才写入）
# --------------------------------------------------------------------------- #

#: 抽取器的系统提示。「记什么/不记什么」是这个功能成败的关键：
#: 记太宽会把一次性的事也存进去，下次对话模型就会拿过期信息当事实用。
FACT_SYSTEM = """你从一轮对话里挑出**值得长期记住**的稳定事实，输出 JSON 数组。

值得记的：
- 稳定属性：身份、职业、所在地区、设备型号、宠物、常用语言或工具
- 稳定偏好：预算区间、风格偏好、口味、忌口、过敏
- 长期项目：正在做的项目名、技术选型、长期目标

**不要记**：
- 一次性的问题（「今天天气怎么样」）
- 临时状态（「我现在有点忙」）
- 会变的信息（当前时间、股价、天气）
- 从工具结果里读到的、和用户本人无关的公共信息
- 助手说的话、模型自己的推测

输出格式：`[{{"content": "……", "category": "identity"}}]`
category 只能是 identity（身份）、preference（偏好）、project（项目）、other 四选一。
没有任何值得记的就输出 `[]`。用户明确说「记住」的内容一定算数。"""

#: 抽取器的用户提示。``known`` 是已经记过的，用来防止重复写入。
FACT_USER = """【已经记过的（不要重复）】
{known}

【用户这一轮问的】
{question}

【助手这一轮答的】
{answer}

挑出最多 {limit} 条新的稳定事实，输出 JSON 数组。没有就输出 []。"""
